#!/usr/bin/env python3
"""Writes width.rs: the code points a terminal draws in no cell (combining marks Mn/Me and format characters Cf, but
the soft hyphen) and in two (East Asian Width W and F), as sorted ranges, from Python's unicodedata.
Usage: python3 width.py"""
import sys, unicodedata
from pathlib import Path


def ranges(test):
    out, start = [], None
    for point in range(0x110000 + 1):
        inside = point <= 0x10FFFF and test(chr(point))
        if inside and start is None:
            start = point
        elif not inside and start is not None:
            out.append((start, point - 1))
            start = None
    return out


zero = ranges(lambda char: unicodedata.category(char) in ('Mn', 'Me', 'Cf') and char != '\u00ad')
wide = ranges(lambda char: unicodedata.east_asian_width(char) in ('W', 'F'))
lines = [f'//! Generated by width.py from Python {sys.version.split()[0]} unicodedata (Unicode {unicodedata.unidata_version}). Do not edit.',
         '', '/// Code points drawn in no cell: combining marks (Mn, Me), format characters (Cf) but U+00AD.',
         'pub(super) const ZERO: &[(u32, u32)] = &[']
lines += [f'    (0x{a:X}, 0x{b:X}),' for a, b in zero]
lines += ['];', '', '/// Code points drawn in two cells: East Asian Width W and F.', 'pub(super) const WIDE: &[(u32, u32)] = &[']
lines += [f'    (0x{a:X}, 0x{b:X}),' for a, b in wide]
lines += ['];', '']
(Path(__file__).resolve().parent / 'width.rs').write_text('\n'.join(lines))
